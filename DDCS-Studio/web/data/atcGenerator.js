/**
 * data/atcGenerator.js — generate a DDCS Expert tool-change macro (T.nc) from the Settings ATC magazine.
 *
 * The controller auto-runs T.nc on a tool change (`Tn M6`): #1504 = requested tool, #1300 = tool in spindle,
 * #1430+ = tool-length table. This emits a STRAIGHT / linear changer: for each pocket (pocket#·tool#·name·
 * park XYZ from Settings) it moves to the park position and runs the drawbar dance with the configured
 * drawbar output's M-codes (release/clamp). See DDCS-ATC-WORKFLOW.md for the firmware dialect.
 *
 * ⚠ GENERATED TEMPLATE — grounded in the firmware dialect + CORE_TRUTH quirks (G53 needs a VARIABLE not a
 * constant; C-style `IF a==b`, no brackets on a simple IF, no space before the GOTO label). It is NOT
 * validated on a live ATC. Spindle + coolant stop (M5/M9) runs first; drawbar moves wait on the M301/M302
 * sensors — delete those waits if your machine has no drawbar sensors. Per ARCHITECTURE-MULTIUSER.md,
 * Studio only generates — the user reviews every line and dry-runs it on their own machine before cutting.
 */

function num(v, d) { return (v === '' || v == null || isNaN(Number(v))) ? d : Number(v); }

export function generateToolChangeNc(atc, outputs, opts = {}) {
    atc = atc || {};
    const body = !!opts.body;   // INC-B2: emit the executable BODY only (no trailing M99 wrapper) for inlining
    const mag = (Array.isArray(atc.magazine) ? atc.magazine : []).filter(p => p && p.tool !== '' && p.tool != null);
    // Tool name comes from the library (keyed by tool number); fall back to any legacy per-pocket name.
    const nameOf = {};
    (Array.isArray(atc.tools) ? atc.tools : []).forEach((t) => { if (t && t.num != null && t.num !== '') nameOf[Number(t.num)] = t.name || ''; });
    const label = (p) => { const nm = p.name || nameOf[num(p.tool, 0)] || ''; return nm ? ' - ' + nm : ''; };
    const drawbar = (outputs || []).find(o => o.type === 'drawbar') || {};
    const release = (drawbar.onCode || 'M154').trim();   // spindle drawbar OPEN (release tool)
    const clamp = (drawbar.offCode || 'M155').trim();    // spindle drawbar CLOSE (clamp tool)
    const safeZ = num(atc.safeZ, 10);
    const dwell = 500;                                   // ms — drawbar settle

    const L = [];
    const w = (s) => L.push(s);

    w(body ? '(tool-change - INLINED from your ATC config; drawbar codes from Settings -> ATC I/O)' : '(T.nc - tool-change macro generated by DDCS Studio)');
    w('(GENERATED TEMPLATE - review every line + dry-run before cutting. NOT validated on a live ATC.)');
    w('(Straight/linear magazine, ' + mag.length + ' pockets. Drawbar: release ' + release + ' / clamp ' + clamp + '.)');
    w('(#1504=requested tool [Tn M6]  #1300=tool in spindle  #1430+=tool-length table)');
    w('');
    w('IF #1504==#1300 GOTO999            ; requested tool already in spindle');
    w('M5  M9                             ; spindle + coolant OFF before any drawbar action');
    w('M300                              ; wait: spindle stopped (delete if no sensor)');
    w('#4 = ' + safeZ);
    w('G53 G0 Z#4                         ; lift to safe Z (G53 needs a variable)');
    w('');
    w('(===== return the current tool to its pocket =====)');
    w('IF #1300==0 GOTO500               ; spindle empty - nothing to return');
    mag.forEach((p, i) => w('IF #1300==' + num(p.tool, 0) + ' GOTO' + (101 + i) + '         ; current tool -> pocket ' + num(p.pocket, i + 1)));
    w('GOTO500                           ; current tool not in magazine - skip return');
    mag.forEach((p, i) => {
        w('N' + (101 + i) + ' (return T' + num(p.tool, 0) + ' to pocket ' + num(p.pocket, i + 1) + label(p) + ')');
        w('#1 = ' + num(p.x, 0) + '  #2 = ' + num(p.y, 0) + '  #3 = ' + num(p.z, 0));
        w('G53 G0 X#1 Y#2'); w('G53 G0 Z#3');
        w(release + '                          ; drawbar release'); w('G04 P' + dwell);
        w('M301                              ; wait: drawbar released (delete if no sensor)');
        w('G53 G0 Z#4'); w('GOTO500');
    });
    w('');
    w('N500 (===== fetch the requested tool =====)');
    mag.forEach((p, i) => w('IF #1504==' + num(p.tool, 0) + ' GOTO' + (201 + i) + '         ; requested tool -> pocket ' + num(p.pocket, i + 1)));
    w('#1505 = 1(Tool not in magazine!) ; requested tool has no pocket');
    w('GOTO999');
    mag.forEach((p, i) => {
        w('N' + (201 + i) + ' (fetch T' + num(p.tool, 0) + ' from pocket ' + num(p.pocket, i + 1) + label(p) + ')');
        w('#1 = ' + num(p.x, 0) + '  #2 = ' + num(p.y, 0) + '  #3 = ' + num(p.z, 0));
        w('G53 G0 X#1 Y#2');
        w(release + '                          ; open collet BEFORE descending over the tool shank');
        w('M301                              ; wait: drawbar released (delete if no sensor)');
        w('G53 G0 Z#3                          ; descend over the tool');
        w(clamp + '                          ; drawbar clamp'); w('G04 P' + dwell);
        w('M302                              ; wait: drawbar clamped (delete if no sensor)');
        w('G53 G0 Z#4'); w('#1300 = #1504               ; record the new tool'); w('GOTO999');
    });
    w('');
    w('N999');
    if (!body) w('M99');   // INC-B2: M99 = subprogram-return wrapper, omitted when inlined
    return L.join('\n');
}
