import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://127.0.0.1:8799', { waitUntil: 'networkidle' });
await page.waitForTimeout(1500);
await page.locator('.hdr-tabs .tab[data-app="gateway"]').click();
await page.waitForTimeout(800);
const out = [];
out.push('sub-tabs (6): ' + ((await page.locator('#gateway-app .tabs .tab').count()) === 6));
out.push('default is Tracker: ' + (await page.locator('#gateway-app .tabs .tab.on').textContent()));
out.push('big pct shown: ' + (await page.locator('#gateway-app .bt-pct').textContent().catch(() => '(none)')));
out.push('job name: ' + (await page.locator('#gateway-app .bt-job').textContent().catch(() => '(none)')));
await page.screenshot({ path: 'verification/big-tracker.png' });
await page.locator('#gateway-app .tabs .tab', { hasText: 'Queue' }).click();
await page.waitForTimeout(600);
const labels = await page.locator('#gateway-app .section-label').allTextContents();
out.push('queue view sections: ' + JSON.stringify(labels));
console.log(out.join('\n'));
if (errors.length) console.log('PAGE ERRORS:\n' + errors.join('\n'));
await browser.close();
